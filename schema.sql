create or replace function public.broadcast_support_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_thread_id text;
begin
  if tg_op = 'DELETE' then
    v_thread_id := old.thread_id;
  else
    v_thread_id := new.thread_id;
  end if;
  -- The public payload is only a wake-up ping. It never contains a message,
  -- contact detail, token hash, or other row data. The guest must re-auth via RPC.
  begin
    perform realtime.send(
      jsonb_build_object('changed', true),
      'support_changed',
      'support:' || v_thread_id,
      false
    );
  exception when others then
    -- Do not fail a support message if today's Realtime partition is unavailable.
    null;
  end;
  return null;
end;
$$;
revoke all on function public.broadcast_support_change() from public, anon, authenticated;
drop trigger if exists support_thread_broadcast on public.support_threads;
create trigger support_thread_broadcast
after insert or update or delete on public.support_threads
for each row execute function public.broadcast_support_change();

