drop function if exists public.submit_support_message(text, text, text, text, text);
create function public.submit_support_message(
  p_thread_id text,
  p_secret text,
  p_customer_name text,
  p_customer_contact text,
  p_text text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_thread public.support_threads%rowtype;
  v_message jsonb;
  v_created boolean := false;
  v_count integer;
  v_secret_hash text;
begin
  if coalesce(p_thread_id, '') !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' then
    raise exception 'شناسه گفتگوی معتبر نیست';
  end if;
  if coalesce(p_secret, '') !~ '^[0-9a-f]{64}$' then
    raise exception 'کلید گفتگوی معتبر نیست';
  end if;
  v_secret_hash := public.hash_guest_secret(p_secret);
  if length(btrim(coalesce(p_text, ''))) < 1 or length(p_text) > 2000 then
    raise exception 'متن پیام باید بین ۱ تا ۲۰۰۰ نویسه باشد';
  end if;
  if length(coalesce(p_customer_name, '')) > 80 or length(coalesce(p_customer_contact, '')) > 120 then
    raise exception 'اطلاعات تماس معتبر نیست';
  end if;

  v_message := jsonb_build_object(
    'sender', 'customer',
    'text', btrim(p_text),
    'time', to_char(now() at time zone 'Asia/Tehran', 'HH24:MI'),
    'created_at', to_char(now() at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
  );

  select * into v_thread
  from public.support_threads t
  where t.thread_id = p_thread_id
  for update;

  if not found then
    insert into public.support_threads (
      thread_id, user_id, customer_name, customer_contact, status, messages, guest_token_hash
    ) values (
      p_thread_id, auth.uid(), coalesce(nullif(btrim(p_customer_name), ''), 'کاربر بلکسی گیم'),
      btrim(coalesce(p_customer_contact, '')), 'open', jsonb_build_array(v_message), v_secret_hash
    ) on conflict (thread_id) do nothing;
    get diagnostics v_count = row_count;
    v_created := (v_count = 1);
    select * into v_thread from public.support_threads t where t.thread_id = p_thread_id for update;
  end if;

  if v_thread.thread_id is null or v_thread.guest_token_hash is distinct from v_secret_hash then
    raise exception 'گفتگو پیدا نشد یا کلید گفتگو نادرست است' using errcode = '42501';
  end if;
  if v_thread.status = 'closed' then
    raise exception 'این گفتگو بسته شده است';
  end if;

  if not v_created then
    if jsonb_array_length(coalesce(v_thread.messages, '[]'::jsonb)) >= 500 then
      raise exception 'ظرفیت این گفتگو تکمیل شده است';
    end if;
    update public.support_threads
    set messages = coalesce(messages, '[]'::jsonb) || jsonb_build_array(v_message),
        status = 'open', updated_at = now()
    where thread_id = p_thread_id
    returning * into v_thread;
  end if;

  return jsonb_build_object(
    'thread_id', v_thread.thread_id,
    'customer_name', v_thread.customer_name,
    'customer_contact', v_thread.customer_contact,
    'status', v_thread.status,
    'messages', v_thread.messages,
    'updated_at', v_thread.updated_at
  );
end;
$$;
revoke all on function public.submit_support_message(text, text, text, text, text) from public, anon, authenticated;
grant execute on function public.submit_support_message(text, text, text, text, text) to anon, authenticated;

