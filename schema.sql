create or replace function public.release_order_inventory()
returns trigger
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_items jsonb;
  v_line jsonb;
  v_product_id bigint;
  v_quantity integer;
  v_release boolean := false;
begin
  if tg_op = 'DELETE' then
    v_items := old.items;
    v_release := old.inventory_reserved and old.status in ('pending', 'processing');
  else
    if old.status = 'cancelled' and new.status <> 'cancelled' then
      raise exception 'سفارش لغوشده را نمی‌توان دوباره فعال کرد';
    end if;
    if old.status <> 'cancelled' and new.status = 'cancelled' then
      v_items := old.items;
      v_release := old.inventory_reserved and old.status in ('pending', 'processing');
      new.inventory_reserved := false;
    end if;
  end if;

  if v_release and pg_catalog.jsonb_typeof(v_items) = 'array' then
    for v_line in select value from pg_catalog.jsonb_array_elements(v_items) as e(value) loop
      v_product_id := (v_line ->> 'id')::bigint;
      v_quantity := (v_line ->> 'qty')::integer;
      if v_product_id > 0 and v_quantity > 0 then
        update public.products
        set stock = stock + v_quantity
        where id = v_product_id and stock is not null;
      end if;
    end loop;
  end if;

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;
revoke all on function public.release_order_inventory() from public, anon, authenticated;
drop trigger if exists orders_release_inventory on public.orders;
create trigger orders_release_inventory
before update of status or delete on public.orders
for each row execute function public.release_order_inventory();
