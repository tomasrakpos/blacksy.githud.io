-- 8) Secure order RPCs
-- -----------------------------------------------------------------------------
-- Hash 256-bit, lower-case hex bearer secrets inside PostgreSQL. RPC callers
-- never pass a reusable database hash; only the raw secret crosses TLS and the
-- stored capability remains non-replayable if the table is exposed.
create or replace function public.hash_guest_secret(p_secret text)
returns text
language sql
immutable
set search_path = ''
as $$
  select case
    when coalesce(p_secret, '') ~ '^[0-9a-f]{64}$'
      then pg_catalog.encode(pg_catalog.sha256(pg_catalog.decode(p_secret, 'hex')), 'hex')
    else null
  end;
$$;
revoke all on function public.hash_guest_secret(text) from public, anon, authenticated;

drop function if exists public.create_order(text, text, text, text, text, text, jsonb, text);
create function public.create_order(
  p_customer_name text,
  p_customer_phone text,
  p_address text,
  p_postal_code text,
  p_shipping_method text,
  p_payment_method text,
  p_items jsonb,
  p_guest_secret text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
set row_security = off
as $$
declare
  v_user_id uuid := auth.uid();
  v_order_id uuid := pg_catalog.gen_random_uuid();
  v_order_code text := 'BG-' || upper(left(replace(pg_catalog.gen_random_uuid()::text, '-', ''), 16));
  v_line jsonb;
  v_product public.products%rowtype;
  v_product_id bigint;
  v_quantity integer;
  v_total bigint := 0;
  v_snapshot jsonb := '[]'::jsonb;
  v_guest_hash text;
  v_reserves_stock boolean := false;
  v_result jsonb;
begin
  if length(btrim(coalesce(p_customer_name, ''))) < 2 or length(p_customer_name) > 100 then
    raise exception 'نام گیرنده معتبر نیست';
  end if;
  if length(btrim(coalesce(p_customer_phone, ''))) < 6 or length(p_customer_phone) > 24 then
    raise exception 'شماره تماس معتبر نیست';
  end if;
  if length(btrim(coalesce(p_address, ''))) < 5 or length(p_address) > 500 then
    raise exception 'نشانی معتبر نیست';
  end if;
  if length(coalesce(p_postal_code, '')) > 16 then
    raise exception 'کد پستی معتبر نیست';
  end if;
  if length(coalesce(p_shipping_method, '')) > 100 or length(coalesce(p_payment_method, '')) > 60 then
    raise exception 'روش ارسال یا پرداخت معتبر نیست';
  end if;
  if coalesce(nullif(btrim(p_shipping_method), ''), 'ارسال بلکسی گیم — رایگان') not in ('ارسال بلکسی گیم — رایگان', 'ارسال سریع') then
    raise exception 'روش ارسال معتبر نیست';
  end if;
  if coalesce(nullif(btrim(p_payment_method), ''), 'پرداخت اینترنتی') not in ('پرداخت اینترنتی', 'پرداخت در محل') then
    raise exception 'روش پرداخت معتبر نیست';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 30 then
    raise exception 'اقلام سفارش معتبر نیستند';
  end if;

  if v_user_id is null then
    if coalesce(p_guest_secret, '') !~ '^[0-9a-f]{64}$' then
      raise exception 'توکن سفارش مهمان معتبر نیست';
    end if;
    v_guest_hash := public.hash_guest_secret(p_guest_secret);
  else
    v_guest_hash := null;
  end if;

  for v_line in select value from jsonb_array_elements(p_items) as e(value) loop
    begin
      v_product_id := (v_line ->> 'id')::bigint;
      v_quantity := (v_line ->> 'qty')::integer;
    exception when others then
      raise exception 'شناسه یا تعداد محصول معتبر نیست';
    end;
    if v_quantity < 1 or v_quantity > 20 then
      raise exception 'تعداد هر کالا باید بین ۱ و ۲۰ باشد';
    end if;
    if exists (
      select 1 from pg_catalog.jsonb_array_elements(v_snapshot) as saved(value)
      where (saved.value ->> 'id')::bigint = v_product_id
    ) then
      raise exception 'هر کالا باید فقط یک‌بار در سبد سفارش فرستاده شود';
    end if;

    select * into v_product
    from public.products p
    where p.id = v_product_id and p.is_published = true and p.price is not null and p.price > 0
    for update;
    if not found then
      raise exception 'یکی از کالاها موجود نیست یا قیمت آن تأیید نشده است';
    end if;
    if v_product.stock is not null and v_product.stock < v_quantity then
      raise exception 'موجودی یکی از کالاها کافی نیست';
    end if;
    if v_product.stock is not null then
      update public.products
      set stock = stock - v_quantity
      where id = v_product.id and stock >= v_quantity;
      if not found then raise exception 'موجودی یکی از کالاها کافی نیست'; end if;
      v_reserves_stock := true;
    end if;

    v_total := v_total + (v_product.price * v_quantity);
    v_snapshot := v_snapshot || jsonb_build_array(jsonb_build_object(
      'id', v_product.id,
      'name', v_product.name,
      'qty', v_quantity,
      'price', v_product.price
    ));
  end loop;

  insert into public.orders (
    id, order_code, user_id, customer_name, customer_phone, address, postal_code,
    shipping_method, payment_method, status, total_amount, items, guest_token_hash, inventory_reserved
  ) values (
    v_order_id, v_order_code, v_user_id, btrim(p_customer_name), btrim(p_customer_phone),
    btrim(p_address), btrim(coalesce(p_postal_code, '')),
    coalesce(nullif(btrim(p_shipping_method), ''), 'ارسال بلکسی گیم — رایگان'),
